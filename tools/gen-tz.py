"""Regenerate src/shared/tz-offsets.ts: country -> [min, max] UTC offset (minutes) in 2026,
from the system tzdata zone.tab. Run: python3 tools/gen-tz.py"""
import zoneinfo, datetime, json, pathlib
m = {}
for line in open('/usr/share/zoneinfo/zone.tab'):
    if line.startswith('#'):
        continue
    p = line.rstrip('\n').split('\t'); cc, tz = p[0], p[2]
    try:
        z = zoneinfo.ZoneInfo(tz)
    except Exception:
        continue
    for mon in (1, 7):
        off = int(datetime.datetime(2026, mon, 15, 12, tzinfo=z).utcoffset().total_seconds() // 60)
        lo, hi = m.get(cc, (off, off)); m[cc] = (min(lo, off), max(hi, off))
out = ("// Generated by tools/gen-tz.py from tzdata zone.tab (2026 offsets, minutes from UTC). Country -> [min, max].\n"
       "export const COUNTRY_UTC_OFFSETS: Record<string, [number, number]> = "
       + json.dumps({k: list(v) for k, v in sorted(m.items())}, separators=(',', ':')) + ";\n")
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/shared/tz-offsets.ts').write_text(out)
print(len(m), 'countries')
